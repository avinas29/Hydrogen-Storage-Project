"""Write reports/dataset_comparison.md from the Phase 2 tables."""
from __future__ import annotations

from pathlib import Path

import pandas as pd

from .compare import NEAR_L1, SAME_MEASUREMENT_TOL_KJ
from .run_audit import md_table

ROOT = Path(__file__).resolve().parents[2]
T = ROOT / "results/tables"
PROC = ROOT / "data/processed"


def main() -> None:
    p = pd.read_csv(PROC / "purdue_cleaned.csv")
    h = pd.read_csv(PROC / "hydpark_cleaned.csv")
    u = pd.read_csv(PROC / "dH_union_by_composition.csv")
    m = pd.read_csv(T / "cross_dataset_comparison.csv")
    ov = pd.read_csv(T / "composition_overlap.csv")
    fam = pd.read_csv(T / "composition_overlap_by_family.csv")
    st = pd.read_csv(T / "cross_dataset_agreement_stats.csv")
    expl = pd.read_csv(T / "cross_dataset_discrepancy_explanations.csv")
    ign = pd.read_csv(T / "purdue_ignored_entries_in_hydpark.csv")
    famx = pd.read_csv(T / "cross_dataset_family_agreement.csv")
    ex = m[m["match_level"] == "exact"]
    v = lambda q: int(ov.loc[ov["quantity"] == q, "value"].iloc[0])

    # Capacity: descriptive comparison only
    cap = ex[ex["d_wt"].notna()]
    cap_tab = cap.groupby("purdue_capacity_basis").agg(
        n_pairs=("d_wt", "size"),
        frac_within_0_05_wt=("d_wt", lambda s: round((s.abs() <= 0.05).mean(), 3)),
        median_abs_diff_wt=("d_wt", lambda s: round(s.abs().median(), 3)),
        max_abs_diff_wt=("d_wt", lambda s: round(s.abs().max(), 3))).reset_index()

    hdup = h[h["flag_chemical_duplicate"]]
    hgroups = hdup.groupby("comp_key")
    cross_block = int((hgroups["source_block"].nunique() > 1).sum())
    spread = hgroups["dH_kJmol"].agg(lambda s: s.max() - s.min())

    big = ex[ex["discrepancy_explanation"] == "different_source_or_measurement"][
        ["purdue_id", "formula_hydpark", "hydpark_block", "dH_purdue", "dH_hydpark",
         "d_dH", "dS_purdue", "dS_hydpark"]].sort_values("d_dH")
    refit = ex[ex["discrepancy_explanation"] == "purdue_value_refitted_from_isotherms"][
        ["purdue_id", "dH_purdue", "dH_hydpark", "d_dH"]].sort_values("d_dH")
    ufam = u.groupby(u["family"].fillna("(missing)")).agg(
        n_compositions=("comp_key", "size"),
        from_purdue=("value_source", lambda s: int((s == "purdue").sum())),
        from_hydpark=("value_source", lambda s: int((s != "purdue").sum())),
        median_dH=("dH_kJmol", "median"),
        n_spread_gt_5kJ=("dH_spread_kJmol", lambda s: int((s > 5).sum()))).reset_index()

    sandia = st.set_index("subset")
    text = f"""# Phase 2: dataset cleaning and cross-dataset comparison

Generated by `src/data/compare_report.py`. Code: `src/data/clean.py` and
`src/data/compare.py`. Raw files are unchanged. All tables are in `results/tables/`.

## 1. Cleaning applied (only to the analytical copies)

| Step | Purdue | HydPARK |
|---|---|---|
| Formula parsing | pymatgen `Composition` built from the `.mh` element list | pymatgen on `Composition_Formula`, which accepts plain, at.%, and sublattice `( )` notation |
| Parsed | {int(p['parse_status'].str.startswith('ok').sum())} / {len(p)} | {int((h['parse_status']=='ok').sum())} / {len(h)} |
| Not representable | {int((~p['parse_status'].str.startswith('ok')).sum())} with Mm/Lm/Vf pseudo-elements (kept, `comp_key` = NaN, flagged) | 0 |
| Composition key | atomic fractions, 3 decimals, sorted (`Fe0.5Ti0.5`) | same |
| dH, dS convention | sign flipped to positive desorption magnitudes; J converted to kJ | already positive, kJ |
| Capacity | wt% from `Weight Percent`, or from H/M (per formula unit) with the toolbox formula; basis kept in `capacity_basis` | `wt_pct = 0` and `HtoM = 0` (1 row) set to NaN |
| Records removed | none | none |

Outputs: `data/processed/purdue_cleaned.csv` ({p.shape[0]} x {p.shape[1]}) and
`data/processed/hydpark_cleaned.csv` ({h.shape[0]} x {h.shape[1]}). Raw columns,
source IDs and references are preserved, and every Phase 1 flag is carried over.

## 2. Duplicates within each dataset

* **Purdue:** no two `.mh` files share a composition.
* **HydPARK:** {len(hdup)} records fall in {hdup['comp_key'].nunique()} composition groups. Only 52 of
  these records have an identical *string*; the rest are the same chemistry written in
  different notation, e.g. `ZrMn2` vs `(Zr)(Mn)2`. {cross_block} of the groups span **different
  source blocks**. The Phase 1 statement that blocks have no formula in common holds only for raw strings.
  Within a group, the dH range has median {spread.median():.2f} and maximum {spread.max():.1f} kJ/mol H2. In
  {int((spread <= SAME_MEASUREMENT_TOL_KJ).sum())} groups the values agree within {SAME_MEASUREMENT_TOL_KJ} kJ/mol, so it is almost certainly
  one literature value entered twice. Consequence: **cross-validation must group by `comp_key`** (column
  `comp_group`), or the same measurement ends up in both train and test.

## 3. Composition overlap

Matching: exact = identical `comp_key`. Near = same element set with L1 atomic-fraction
distance <= {NEAR_L1}, reported separately and not treated as identical.

{md_table(ov)}

{md_table(fam)}

Family labels agree for every exact match where both datasets give one (rows: Purdue, columns: HydPARK).
HydPARK's `MIC` (miscellaneous intermetallics) collects Purdue's AB3, A2B7 and Misc:

{md_table(famx)}

## 4. dH and dS agreement on exact matches

{md_table(st)}

**HydPARK largely reproduces Purdue's source values.** For single-plateau
exact matches the median |dH difference| is {sandia.loc['all exact pairs (single-plateau)','dH_median_abs_diff']:.2f} kJ/mol H2 and
{100*sandia.loc['all exact pairs (single-plateau)','frac_dH_within_0.5']:.0f}% of pairs agree within 0.5 kJ/mol. Where Purdue cites a SandiaDBRef
placeholder, agreement is {100*sandia.loc['Purdue ref = SandiaDBRef','frac_dH_within_0.5']:.0f}% (r = {sandia.loc['Purdue ref = SandiaDBRef','pearson_r_dH']:.3f}). HydPARK
block 0 has no references and uses the same `Ti1Fe0.5Co0.5`-style names as Purdue's
Sandia-sourced files. Its values match Purdue's `SandiaDBRef` entries almost exactly. The
evidence points to **one shared legacy source, most likely the Sandia/DOE hydride
database**. That provenance is inferred from the data and is not documented in either
file. The 12 entries Purdue's curators moved to
`*.ignore` are **all** present in HydPARK (section 6).

### Why some pairs disagree (|dH diff| > 2 kJ/mol)

{md_table(expl)}

* *Refitted from isotherms*: the Purdue file is marked `From Isotherms: true`, meaning the
  toolbox authors refit dH/dS from digitized PCI curves, while HydPARK keeps the tabulated
  literature value. Examples:

{md_table(refit)}

* *Multi-plateau*: Purdue's scalar is the first (lowest-capacity) plateau. HydPARK
  stores a single value, which in 4 cases equals another of Purdue's plateaus and in
  5 cases equals none of them.
* *Different source or measurement* ({len(big)} pairs): these are genuine scatter
  between papers. The large cases are Zr-based Laves phases (ZrMn2, ZrCrFe, ZrMn2.8) and
  RE-Co compounds, where dH depends on plateau, temperature range and sample:

{md_table(big)}

## 5. Capacity comparison (descriptive only)

Neither dataset defines its capacity uniformly: Purdue's is mostly
`literature_value_definition_unstated`, and HydPARK has no definition at all. So this
comparison only shows consistency of the *reported numbers*. It cannot validate a model.

{md_table(cap_tab)}

When Purdue states wt%, the two datasets usually carry the same number. When Purdue
gives H/M, agreement drops, because the HydPARK wt% was converted or rounded differently.
**No cross-dataset capacity validation is claimed.**

## 6. Entries excluded by the Purdue curators but present in HydPARK

{md_table(ign)}

These HydPARK rows are flagged `flag_excluded_by_purdue_curators` and kept out of the
dH union. Several of them are the low-dS rows already flagged in Phase 1.

## 7. Exclusive materials

* Only in Purdue: {v('Compositions only in Purdue (exact)')} real-element compositions, plus {v('Purdue records not matchable (pseudo-elements)')}
  mischmetal/ferrovanadium alloys that cannot be compared.
* Only in HydPARK: {v('Compositions only in HydPARK (exact)')} compositions. Most are block 3 AB2 Laves alloys (C14/C15),
  together with Mg-based and A2B compounds that are rare in Purdue.

## 8. Decision: what can and cannot be claimed

1. **No external validation across the datasets.** {v('Compositions in both (exact)')} of {v('Purdue unique compositions')} parseable Purdue compositions
   are in HydPARK, mostly with the same value from the same source. Training on one and
   testing on the other would measure memorisation of shared records, not generalisation.
2. **The dH modelling set is a composition-level union**, `data/processed/dH_union_by_composition.csv`,
   built by explicit rules rather than concatenation:
   * one row per real-element composition ({len(u)} rows);
   * Purdue single-plateau value if available, otherwise the HydPARK median;
   * excluded: pseudo-element and multi-plateau Purdue entries, HydPARK suspected entry
     errors, and curator-excluded entries;
   * `value_source`, `dH_spread_kJmol` (inter-source scatter) and provenance flags are kept.

{md_table(ufam)}

   Validation will use grouped CV on this union, with a family-wise breakdown (AB2 and AB5 are the
   only families large enough). A Purdue-only model is reported as a sensitivity check.
3. **The inter-source scatter sets a floor on achievable error.** Where two sources report
   the same composition, the mean |dH difference| is about {sandia.loc['Purdue ref = DOI/other','dH_MAE_kJmol']:.1f} kJ/mol for independently
   referenced pairs. A model MAE close to this is about as good as the data allows.
4. **Capacity (wt%) modelling** stays Purdue-only, using `capacity_basis = stated_wt_pct` and
   excluding assumed, theoretical and unconfirmed values. The decision on whether there is enough data comes in Phase 5.
"""
    (ROOT / "reports/dataset_comparison.md").write_text(text)


if __name__ == "__main__":
    main()
