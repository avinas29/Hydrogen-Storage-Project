"""Write report/content/09_appendix.md from the project result files (no numbers are typed by hand).

Run from the project root:  .venv/bin/python -m report.make_appendices
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "report/content/09_appendix.md"
T, M = ROOT / "results/tables", ROOT / "results/metrics"


def table(key: str, caption: str, df: pd.DataFrame) -> str:
    rows = [f"TAB {key} | {caption}", "| " + " | ".join(map(str, df.columns)) + " |",
            "|" + "---|" * len(df.columns)]
    rows += ["| " + " | ".join("" if pd.isna(v) else str(v) for v in r) + " |" for r in df.itertuples(index=False)]
    return "\n".join(rows) + "\n"


def demo_tables(section_no: int) -> list[str]:
    """Return the markdown tables of a numbered section ('**8. ...') for both scenarios, as written by src.app.demo."""
    text = (ROOT / "reports/platform_demo_scenarios.md").read_text()
    out = []
    for scen in re.split(r"\n## Scenario \d", text)[1:]:
        m = re.search(rf"\*\*{section_no}\. .*?(?=\n\*\*\d+\. |\Z)", scen, re.S)
        out.append(m.group(0) if m else "")
    return out


def md_to_df(block: str, n: int = 0) -> pd.DataFrame:
    tabs = re.findall(r"((?:^\|.*\|[ \t]*\n?)+)", block, re.M)
    lines = [l for l in tabs[n].strip().splitlines() if not re.match(r"^\|[-| ]+\|$", l)]
    cells = [[c.strip() for c in l.strip("|").split("|")] for l in lines]
    return pd.DataFrame(cells[1:], columns=cells[0])


def main():
    parts = []
    # A. descriptors
    f = pd.read_csv(T / "feature_list.csv")
    f = f[f["kept_after_pruning"] & (f["group"] != "family")]
    parts.append("#A Composition Descriptors\n\nThe 38 descriptors used by the ΔH model, in the order of the model input "
                 "(source: `results/tables/feature_list.csv`). Elemental values are from pymatgen; fractions are atomic fractions.\n")
    parts.append(table("featlist", "Descriptors of the ΔH model", f[["feature", "group", "description"]]
                       .rename(columns={"feature": "Descriptor", "group": "Group", "description": "Definition"})))
    # B. additional ML results
    w = pd.read_csv(M / "dH_within_family.csv")
    w = w.assign(**{"MAE (kJ mol⁻¹)": w.apply(lambda r: f"{r.MAE:.2f} ± {r.MAE_sd:.2f}", axis=1),
                    "R²": w["R2"].round(2), "n": w["n"].astype(int)})[["family", "model", "MAE (kJ mol⁻¹)", "R²", "n"]]
    s = pd.read_csv(M / "dH_sensitivity.csv")
    s = s.assign(MAE=s["MAE"].round(2), RMSE=s["RMSE"].round(2), R2=s["R2"].round(2), n=s["n"].astype(int))[
        ["subset", "model", "MAE", "RMSE", "R2", "n"]].rename(columns={"R2": "R²", "MAE": "MAE (kJ mol⁻¹)", "RMSE": "RMSE (kJ mol⁻¹)"})
    parts.append("#A Additional Machine-Learning Results\n\nModels trained and tested within one family (nested grouped CV), "
                 "and the random forest refitted on data subsets (one repeat). Source: `results/metrics/`.\n")
    parts.append(table("withinfam", "Within-family nested grouped cross-validation", w))
    parts.append(table("subsets", "Sensitivity of the ΔH error to the data subset", s))
    # C. data-quality flags
    p = pd.read_csv(ROOT / "data/processed/purdue_cleaned.csv")
    h = pd.read_csv(ROOT / "data/processed/hydpark_cleaned.csv")
    rows = []
    for name, d in (("Purdue", p), ("HydPARK", h)):
        for c in d.columns:
            if c.startswith("flag_") and d[c].dtype == bool and int(d[c].sum()) > 0:
                rows.append((name, c.removeprefix("flag_").replace("_", " "), int(d[c].sum()), len(d)))
    fl = pd.DataFrame(rows, columns=["Dataset", "Flag", "Records flagged", "Records"])
    parts.append("#A Data-Quality Flags\n\nFlags set during the audit (Phase 1–2). Flagged records are kept; the flags decide "
                 "exclusion from the ΔH union, the screening data-quality gate and the evidence class. Source: "
                 "`data/processed/*_cleaned.csv`.\n")
    parts.append(table("flags", "Data-quality flags in the cleaned datasets", fl))
    parts.append("FIG missing | report/figures/existing/fig10_missing_data.png | 16 | Missing-data map of the Purdue "
                 "(left, sorted by family) and HydPARK (right, file order) records. Percentages give the fraction of "
                 "records in which the property is present; missing values are shown as missing, not as zero.\n")
    # D. Lab candidates
    lab = demo_tables(8)
    parts.append("#A ML-Generated Candidates of the Demonstration Scenarios\n\nCandidates generated by the Discovery Lab "
                 "(source: `reports/platform_demo_scenarios.md`). **Proposed compositions, not validated:** ΔH is the "
                 "ML prediction with its 80% interval, ΔS is the assumed family median, capacity is not predicted. "
                 "Temperatures are those needed for the scenario's delivery pressure.\n")
    keep = ["formula", "dH_pred_kJmol", "dH_low", "dH_high", "nn_L1", "T_at_Ptarget_C", "nearest_known", "nearest_known_dH_exp"]
    ren = {"formula": "Candidate", "dH_pred_kJmol": "ΔH pred.", "dH_low": "80% low", "dH_high": "80% high", "nn_L1": "d~NN~",
           "T_at_Ptarget_C": "T est. (°C)", "nearest_known": "Nearest known", "nearest_known_dH_exp": "Its ΔH (exp.)"}
    for i, (blk, lab_name) in enumerate(zip(lab, ["mobile", "industrial"])):
        parts.append(table(f"lab{i}", f"Generation summary, scenario {i + 1} ({lab_name})", md_to_df(blk, 0)))
        parts.append(table(f"labc{i}", f"Top candidates, scenario {i + 1} ({lab_name}); ΔH in kJ mol⁻¹",
                           md_to_df(blk, 1)[keep].rename(columns=ren)))
    # E. scenario rankings
    rk = demo_tables(5)
    parts.append("#A Scenario Rankings\n\nTop eight experimental materials of each scenario as produced by the "
                 "Application Requirement Designer (source: `reports/platform_demo_scenarios.md`). Capacities are "
                 "reported, material-level values; mass is the alloy mass for the scenario's hydrogen quantity.\n")
    cols = ["rank", "name", "family", "evidence_class", "score", "T_required_C", "wt_pct", "heat_MJ_per_kgH2", "material_mass_kg"]
    ren = {"rank": "Rank", "name": "Material", "family": "Family", "evidence_class": "Evidence", "score": "Score",
           "T_required_C": "T needed (°C)", "wt_pct": "wt%", "heat_MJ_per_kgH2": "Q (MJ kg⁻¹)", "material_mass_kg": "Alloy mass (kg)"}
    for i, (blk, nm) in enumerate(zip(rk, ["mobile", "industrial buffer"])):
        parts.append(table(f"rank{i}", f"Ranking, scenario {i + 1} ({nm})", md_to_df(blk, 0)[cols].rename(columns=ren)))
    # F. characterisation matrix
    cm = pd.read_csv(T / "characterisation_matrix.csv")
    parts.append("#A Proposed Characterisation Matrix\n\n**Proposed future work only; none of these measurements was made "
                 "in this project.** Source: `results/tables/characterisation_matrix.csv`.\n")
    parts.append(table("charmatrix", "Proposed synthesis and characterisation techniques",
                       cm.rename(columns={"technique": "Technique", "families": "Families",
                                          "property measured": "Property measured",
                                          "gap in this project it addresses": "Gap it addresses"})))
    OUT.write_text("\n".join(parts))
    print("wrote", OUT, sum(1 for l in OUT.read_text().splitlines() if l.startswith("TAB ")), "tables")


if __name__ == "__main__":
    main()
